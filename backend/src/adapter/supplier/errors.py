"""Ошибки адаптеров источников.

Сбой обхода остаётся в слое адаптеров: сервис фиксирует его в журнале обхода и
не разбирает причину. Адаптер поднимает ошибку, только если источник не прочитан
целиком; пропуск отдельной страницы он логирует и продолжает обход.
"""


class ProviderError(Exception):
    """Базовая ошибка адаптера источника."""


class SourceUnavailableError(ProviderError):
    """Источник недоступен: обход не начался или прерван на входе."""


class ContentFormatError(ProviderError):
    """Документ получен, но не разобран: содержимое не соответствует формату."""


class BotProtectionError(SourceUnavailableError):
    """Источник отвечает проверкой на робота: обход не обходит защиту и завершается."""
